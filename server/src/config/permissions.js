export function permissionsForRole(role) {
  return [...(ROLE_PERMISSIONS[role] ?? CUSTOMER_PERMISSIONS)];
}

export function hasPermission(role, permission) {
  return Boolean(ROLE_PERMISSIONS[role]?.includes(permission));
}

